"""Характер помощника: обычный или с матом (swearing: true в config.yaml)."""

from __future__ import annotations

import random

SWEAR_NOTE = """

Стиль речи: общайся как свой пацан — неформально, на «ты», с матом. Мат используй как междометия \
и для эмоций («бля», «нихуя себе», «заебись», «пиздец»), а не чтобы унизить. Не оскорбляй пользователя \
всерьёз и никого по национальности, полу, внешности и т.п. Всё так же коротко и по делу: мат — приправа, \
а не вместо ответа."""

# Готовые фразы, которые помощник говорит без нейросети, и их матерные версии.
SWEAR_PHRASES: dict[str, list[str]] = {
    "Открываю.": ["Открываю, бля.", "Ща открою.", "Опа, открываю нахуй."],
    "Сделал громче.": ["Ебашу громче.", "Громче, заебись.", "Сделал погромче, бля."],
    "Сделал тише.": ["Тише, тише, бля.", "Убавил нахуй.", "Сделал потише."],
    "Звук выключен.": ["Заткнул звук нахуй.", "Тишина, бля."],
    "Готово.": ["Готово, бля.", "Сделано, заебись.", "Есть."],
    "Следующий.": ["Следующий, бля.", "Переключил нахуй."],
    "Предыдущий.": ["Назад, бля.", "Вернул предыдущий."],
    "Свернул.": ["Свернул всё нахуй.", "Всё свернул, бля."],
    "Блокирую.": ["Блокирую, бля.", "Закрыл комп нахуй."],
    "Скриншот сохранён.": ["Скрин сохранил, заебись.", "Заскринил, бля."],
    "Напоминания отменены.": ["Напоминалки снёс нахуй.", "Все напоминания похерил."],
    "Слушаю.": ["Слушаю, бля.", "Чё надо?", "Ну?"],
    "Хорошо.": ["Окей, бля.", "Лады."],
    "Начинаем с чистого листа.": ["Всё, забыл нахуй, начинаем заново.", "Чистый лист, бля."],
    "Ничего толкового не нашёл.": ["Нихуя толкового не нашёл.", "Пусто, бля, ничего не нашёл."],
    "Поиск в интернете сейчас недоступен.": ["Интернет-поиск сдох, бля.", "Поиск не отвечает нахуй."],
    "Игровой режим включён. Удачной игры.": ["Игровой режим, бля. Лови трофеев.", "Всё, не мешаю, рыбачь."],
    "Игровой режим выключен.": ["Игровой режим вырубил.", "Всё, обычный режим, бля."],
    "Слушаю без имени. Скажи «стоп», чтобы перестал.": ["Всё, слушаю постоянно, бля. Скажешь «стоп» — заткнусь.",
                                                        "Окей, теперь слушаю всё. «Стоп» — и я отвалю."],
    "Окей, теперь только по имени.": ["Лады, теперь только по имени.", "Всё, не слушаю. Зови по имени, бля."],
    "Отключаюсь. Хорошего дня.": ["Всё, сваливаю. Давай, бро.", "Отключаюсь нахуй. Бывай."],
}


def phrase(text: str, swearing: bool) -> str:
    """Возвращает готовую фразу в нужном стиле."""
    if swearing and text in SWEAR_PHRASES:
        return random.choice(SWEAR_PHRASES[text])
    if swearing and text.startswith("Напомню через"):
        return text.replace("Напомню через", "Заебись, напомню через", 1)
    if swearing and text.startswith("Ищу:"):
        return random.choice(["Ща поищу, бля:", "Ищу нахуй:", "Секунду, ищу:"]) + text[4:]
    if swearing and text.startswith("Напоминаю:"):
        return text.replace("Напоминаю:", "Эй, бля, напоминаю:", 1)
    return text
